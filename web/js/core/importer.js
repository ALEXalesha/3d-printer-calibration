// Import settings from your own G-code - twin of python/calib3d/core/importer.py.
(function () {
  'use strict';
  const root = typeof globalThis !== 'undefined' ? globalThis : window;
  const C3D = root.C3D || (root.C3D = {});
  const isNode = typeof module === 'object' && module.exports;
  if (isNode) require('./num.js');
  const { pyRound } = C3D.num;

  const LAYER_MARKERS = [';LAYER_CHANGE', ';LAYER:', '; CHANGE_LAYER'];
  const END_MARKERS = [';TYPE:Custom', ';TIME_ELAPSED:', '; filament end gcode', '; MACHINE_END_GCODE_START', ';End of Gcode',
    '; EXECUTABLE_BLOCK_END', '; CONFIG_BLOCK_START', '; prusaslicer_config = begin', '; SuperSlicer_config = begin'];
  const STOP_MARKERS = ['; EXECUTABLE_BLOCK_END', ';End of Gcode', '; CONFIG_BLOCK_START', '; prusaslicer_config = begin',
    '; SuperSlicer_config = begin', ';SETTING_3 '];
  const DROP = /^(M73\b|M486\b|EXCLUDE_OBJECT_DEFINE\b|EXCLUDE_OBJECT_START\b|EXCLUDE_OBJECT_END\b|;TYPE:|;WIDTH:|;HEIGHT:|;TIME_ELAPSED:|; *thumbnail|; *[A-Za-z_][A-Za-z0-9_ ()[\]]* = )/i;
  const KV = /^; *([A-Za-z0-9_]+) *= *(.*)$/;
  const FLAVORS = { klipper: 'klipper', marlin: 'marlin', marlin2: 'marlin', marlinlegacy: 'marlin',
    reprapfirmware: 'rrf', reprap: 'rrf', rrf: 'rrf', griffin: 'marlin', ultigcode: 'marlin' };
  const BED_TYPES = { 'textured pei plate': 'textured_plate_temp', 'high temp plate': 'hot_plate_temp',
    'smooth pei plate': 'hot_plate_temp', 'cool plate': 'cool_plate_temp', 'engineering plate': 'eng_plate_temp',
    'textured cool plate': 'textured_cool_plate_temp', 'supertack plate': 'supertack_plate_temp' };

  const startsAny = (s, list) => list.some((m) => s.startsWith(m));
  const has = (o, k) => Object.prototype.hasOwnProperty.call(o, k);

  function firstNum(v) {
    const m = /[-+]?\d+(?:\.\d+)?/.exec(v || '');
    return m ? parseFloat(m[0]) : null;
  }

  function shape(v) {
    const pts = [];
    for (const part of (v || '').split(',')) {
      const m = /^\s*([-+]?\d+(?:\.\d+)?)x([-+]?\d+(?:\.\d+)?)\s*$/.exec(part);
      if (m) pts.push([parseFloat(m[1]), parseFloat(m[2])]);
    }
    if (pts.length < 3) return null;
    const xs = pts.map((p) => p[0]), ys = pts.map((p) => p[1]);
    const x = Math.max(...xs) - Math.min(...xs), y = Math.max(...ys) - Math.min(...ys);
    let origin = Math.min(...xs) < -1 && Math.min(...ys) < -1 ? 'center' : 'corner';
    const sh = pts.length > 8 ? 'round' : 'rect';
    if (sh === 'round') origin = 'center';
    return [x, y, origin, sh];
  }

  function detectSlicer(head) {
    const m = /generated by (\S+)/i.exec(head) || /Generated with (\S+)/.exec(head);
    const name = (m ? m[1] : '').toLowerCase();
    for (const [key, sid] of [['orcaslicer', 'orca'], ['elegooslicer', 'elegoo'], ['bambustudio', 'bambu'],
      ['prusaslicer', 'prusa'], ['superslicer', 'superslicer'], ['cura', 'cura']]) {
      if (name.indexOf(key) >= 0) return sid;
    }
    if (head.indexOf(';FLAVOR:') >= 0) return 'cura';
    return null;
  }

  function settings(lines) {
    const out = {};
    const cura = [];
    for (const line of lines) {
      if (line.startsWith(';SETTING_3 ')) { cura.push(line.slice(11)); continue; }
      const m = KV.exec(line);
      if (m) out[m[1]] = m[2].trim();
    }
    if (cura.length) {
      const blob = cura.join('');
      const re = /(?:^|\\n)([a-z_0-9]+) = ([^\\]*)/g;
      let m;
      while ((m = re.exec(blob))) if (!has(out, m[1])) out[m[1]] = m[2].trim();
    }
    return out;
  }

  function detectFirmware(cfg, parts) {
    const flavor = (cfg.gcode_flavor || cfg.FLAVOR || '').trim().toLowerCase();
    if (has(FLAVORS, flavor)) return [FLAVORS[flavor], 'header'];
    const joined = parts.join('\n');
    if (/^(SET_PRESSURE_ADVANCE|SET_VELOCITY_LIMIT|SET_PRINT_STATS_INFO|EXCLUDE_OBJECT_DEFINE)\b/m.test(joined)) return ['klipper', 'commands'];
    if (/^M572\s+D/m.test(joined) || /^G10\s+P\d+\s+[SR]/m.test(joined)) return ['rrf', 'commands'];
    if (/^M572\s+S/m.test(joined)) return ['marlin', 'commands'];
    if (/^M900\b/m.test(joined)) return ['marlin', 'commands'];
    return [null, null];
  }

  function regionStart(lines) {
    let begin = 0;
    for (let i = 0; i < lines.length; i++) {
      if (lines[i].startsWith('; EXECUTABLE_BLOCK_START')) { begin = i + 1; break; }
      if (startsAny(lines[i], LAYER_MARKERS)) break;
    }
    let firstLayer = null;
    for (let i = begin; i < lines.length; i++) if (startsAny(lines[i], LAYER_MARKERS)) { firstLayer = i; break; }
    if (begin === 0 && firstLayer) {
      let i = 0;
      while (i < firstLayer && (lines[i].startsWith(';') || !lines[i].trim())) i++;
      begin = i;
    }
    return [begin, firstLayer];
  }

  function regionEnd(lines) {
    let lastLayer = null;
    for (let i = lines.length - 1; i >= 0; i--) if (startsAny(lines[i], LAYER_MARKERS)) { lastLayer = i; break; }
    if (lastLayer === null) return [null, null];
    let start = null;
    for (let i = lastLayer + 1; i < lines.length; i++) if (startsAny(lines[i], END_MARKERS)) { start = i; break; }
    if (start === null) return [null, null];
    let stop = lines.length;
    for (let i = start; i < lines.length; i++) {
      if (i > start && startsAny(lines[i], STOP_MARKERS)) { stop = i; break; }
      if (i === start && startsAny(lines[i], STOP_MARKERS) && !lines[i].startsWith(';TYPE:Custom')) return [null, null];
    }
    return [start, stop];
  }

  function rstrip(s) { return s.replace(/\s+$/, ''); }

  function clean(lines) {
    const out = [];
    for (const line of lines) {
      const s = rstrip(line);
      if (DROP.test(s.trim())) continue;
      out.push(s);
    }
    while (out.length && !out[0].trim()) out.shift();
    while (out.length && !out[out.length - 1].trim()) out.pop();
    return out;
  }

  function cmdOf(line) {
    const code = line.split(';', 1)[0].trim();
    return code ? code.toUpperCase().split(/\s+/)[0] : '';
  }

  function partition(line) {
    const i = line.indexOf(';');
    return i < 0 ? [line, '', ''] : [line.slice(0, i), ';', line.slice(i + 1)];
  }

  function substitute(lines, temps, part) {
    const t1 = temps.first, t = temps.nozzle, bed = temps.bed, ftype = temps.type;
    const out = [], report = [];
    const numEq = (s, v) => v !== null && v !== undefined && Math.abs(parseFloat(s) - v) < 1e-9;
    for (let i = 0; i < lines.length; i++) {
      const line = lines[i];
      let nw = line;
      let [code, sep, comment] = partition(line);
      const cmd = cmdOf(line);
      if (cmd === 'M104' || cmd === 'M109') {
        code = code.replace(/(\bS)(\d+(?:\.\d+)?)\b/g, (all, a, b) => (numEq(b, t1) ? a + '{first_layer_nozzle_temp}' : numEq(b, t) ? a + '{nozzle_temp}' : all));
        nw = code + sep + comment;
      } else if (cmd === 'M140' || cmd === 'M190') {
        code = code.replace(/(\bS)(\d+(?:\.\d+)?)\b/g, (all, a, b) => (numEq(b, bed) ? a + '{bed_temp}' : all));
        nw = code + sep + comment;
      } else if (cmd === 'M6211') {
        code = code.replace(/(\b[QRS])(\d+(?:\.\d+)?)\b/g, (all, a, b) => (numEq(b, t1) ? a + '{first_layer_nozzle_temp}' : all));
        nw = code + sep + comment;
      } else if (cmd === 'SET_PRINT_STATS_INFO') {
        nw = line.replace(/TOTAL_LAYER=\d+/g, 'TOTAL_LAYER={total_layers}');
      } else if (/\b(BED|BED_TEMP|HOTEND|EXTRUDER|EXTRUDER_TEMP|NOZZLE|NOZZLE_TEMP)=\d/i.test(code)) {
        code = code.replace(/\b(BED_TEMP|BED|HOTEND|EXTRUDER_TEMP|EXTRUDER|NOZZLE_TEMP|NOZZLE)=(\d+(?:\.\d+)?)\b/gi, (all, k, v) => {
          const key = k.toUpperCase();
          if (key.startsWith('BED')) return numEq(v, bed) ? key + '={bed_temp}' : all;
          if (numEq(v, t1)) return key + '={first_layer_nozzle_temp}';
          return all;
        });
        nw = code + sep + comment;
      } else if (line.startsWith(';LAYER_COUNT:')) {
        nw = ';LAYER_COUNT:{total_layers}';
      } else if (line.startsWith(';bed_level_temp:') && bed !== null && bed !== undefined && numEq(line.slice(16).trim() || 'nan', bed)) {
        nw = ';bed_level_temp:{bed_temp}';
      } else if (line.startsWith(';initial_filament:') && ftype && line.slice(18).trim() === ftype) {
        nw = ';initial_filament:{filament_type}';
      }
      if (nw !== line) report.push({ part, line: i + 1, before: line, after: nw });
      out.push(nw);
    }
    return [out, report];
  }

  function parse(text, fileName) {
    const lines = text.replace(/\r\n/g, '\n').replace(/\r/g, '\n').split('\n');
    const [begin, firstLayer] = regionStart(lines);
    const [e0, e1] = regionEnd(lines);
    const head = lines.slice(0, Math.min(lines.length, 400)).join('\n');
    const tail = lines.slice(Math.max(0, lines.length - 4000));
    const cfg = settings(lines.slice(0, Math.min(lines.length, firstLayer || 0)).concat(tail));
    const slicer = detectSlicer(head);
    const startRaw = firstLayer !== null ? lines.slice(begin, firstLayer) : [];
    const endRaw = e0 !== null ? lines.slice(e0, e1) : [];
    for (const line of lines.slice(0, Math.min(lines.length, 400))) {
      if (line.startsWith(';FLAVOR:') && !has(cfg, 'FLAVOR')) cfg.FLAVOR = line.slice(8).trim();
    }
    const fl = firstLayer || 0;
    const [fw, fwFrom] = detectFirmware(cfg, startRaw.concat(endRaw, lines.slice(fl, fl + 3000)));
    const p = {}, m = {};
    const num = (...keys) => {
      for (const k of keys) {
        if (has(cfg, k)) {
          const v = firstNum(cfg[k]);
          if (v !== null) return v;
        }
      }
      return null;
    };
    const sh = shape(cfg.printable_area || cfg.bed_shape);
    if (sh) p.bed = { x: sh[0], y: sh[1], origin: sh[2], shape: sh[3] };
    else if (num('machine_width') && num('machine_depth')) p.bed = { x: num('machine_width'), y: num('machine_depth'), origin: 'corner', shape: 'rect' };
    const z = num('printable_height', 'max_print_height', 'machine_height');
    if (z !== null) { p.bed = p.bed || {}; p.bed.z = z; }
    for (const [key, keys] of [['nozzle', ['nozzle_diameter', 'machine_nozzle_size']],
      ['filament_diameter', ['filament_diameter', 'material_diameter']], ['travel_speed', ['travel_speed', 'speed_travel']]]) {
      const v = num(...keys);
      if (v !== null) p[key] = v;
    }
    const acc = num('machine_max_acceleration_x', 'machine_max_acceleration_extruding');
    if (acc) p.max_accel = Math.trunc(acc);
    const spd = num('machine_max_speed_x', 'machine_max_feedrate_x');
    if (spd) p.max_speed = spd;
    const dacc = num('default_acceleration', 'outer_wall_acceleration');
    if (dacc) p.default_accel = Math.trunc(dacc);
    const r = {};
    for (const [key, keys] of [['length', ['retraction_length', 'retract_length', 'retraction_amount']],
      ['speed', ['retraction_speed', 'retract_speed']], ['z_hop', ['z_hop', 'retract_lift', 'retraction_hop']]]) {
      const v = num(...keys);
      if (v !== null) r[key] = v;
    }
    if (Object.keys(r).length) p.retract = r;
    if (fw) {
      p.firmware = fw;
      if (fw === 'marlin' && /^M572\s+S/m.test(startRaw.concat(lines.slice(fl, fl + 3000)).join('\n'))) {
        p.fw_overrides = { pressure_advance: 'M572 S{v}' };
      }
    }
    let name = cfg.printer_model || cfg.printer_settings_id || '';
    if (!name) {
      for (const line of startRaw) if (line.startsWith(';printer_model:')) { name = line.slice(15).trim(); break; }
    }
    if (name) p.name = name.trim().replace(/^"+|"+$/g, '');
    const ftypeRaw = (cfg.filament_type || cfg.material_type || '').split(';')[0].trim().replace(/^"+|"+$/g, '');
    if (ftypeRaw) m.type = ftypeRaw.toUpperCase();
    let tPrint = num('nozzle_temperature', 'temperature', 'material_print_temperature');
    let tFirst = num('nozzle_temperature_initial_layer', 'first_layer_temperature', 'material_print_temperature_layer_0');
    let bed = null;
    const btype = (cfg.curr_bed_type || '').trim().toLowerCase();
    if (has(BED_TYPES, btype)) bed = num(BED_TYPES[btype] + '_initial_layer', BED_TYPES[btype]);
    if (bed === null) bed = num('first_layer_bed_temperature', 'bed_temperature', 'material_bed_temperature_layer_0', 'material_bed_temperature');
    const fromCode = (cmds) => {
      for (const line of startRaw) {
        if (cmds.indexOf(cmdOf(line)) >= 0) {
          const mm = /\bS(\d+(?:\.\d+)?)/.exec(line.split(';', 1)[0]);
          if (mm && parseFloat(mm[1]) > 0) return parseFloat(mm[1]);
        }
      }
      return null;
    };
    if (tFirst === null) tFirst = fromCode(['M109']) || fromCode(['M104']);
    if (tPrint === null) tPrint = tFirst;
    if (bed === null) bed = fromCode(['M190']) || fromCode(['M140']);
    if (tPrint !== null) m.nozzle_temp = Math.trunc(pyRound(tPrint));
    if (tFirst !== null) m.first_layer_temp = Math.trunc(pyRound(tFirst));
    if (bed !== null) m.bed = Math.trunc(pyRound(bed));
    const pa = num('pressure_advance');
    if (pa !== null) m.pa_default = pa;
    const mvs = num('filament_max_volumetric_speed');
    if (mvs) m.mvs = mvs;

    const temps = { first: tFirst, nozzle: tPrint, bed, type: m.type };
    const [start, rep1] = substitute(clean(startRaw), temps, 'start');
    const [end, rep2] = substitute(clean(endRaw), temps, 'end');
    const wanted = ['bed.x', 'bed.y', 'bed.z', 'nozzle', 'filament_diameter', 'firmware', 'retract.length',
      'retract.speed', 'retract.z_hop', 'material.nozzle_temp', 'material.first_layer_temp', 'material.bed',
      'material.type', 'start_gcode', 'end_gcode'];
    const b = p.bed || {};
    const hv = { 'bed.x': has(b, 'x'), 'bed.y': has(b, 'y'), 'bed.z': has(b, 'z'), nozzle: has(p, 'nozzle'),
      filament_diameter: has(p, 'filament_diameter'), firmware: has(p, 'firmware'), 'retract.length': has(r, 'length'),
      'retract.speed': has(r, 'speed'), 'retract.z_hop': has(r, 'z_hop'), 'material.nozzle_temp': has(m, 'nozzle_temp'),
      'material.first_layer_temp': has(m, 'first_layer_temp'), 'material.bed': has(m, 'bed'), 'material.type': has(m, 'type'),
      start_gcode: start.length > 0, end_gcode: end.length > 0 };
    const warnings = [];
    if (slicer === 'bambu') warnings.push('bambu');
    if (!fw) warnings.push('firmware_unknown');
    return { slicer, file: fileName || '', printer: p, material: m, start_gcode: start, end_gcode: end,
      replaced: rep1.concat(rep2), found: wanted.filter((k) => hv[k]), missing: wanted.filter((k) => !hv[k]),
      firmware_from: fwFrom, warnings };
  }

  function toProfiles(imp, basePrinter, baseMaterial) {
    const clone = (x) => JSON.parse(JSON.stringify(x));
    const p = clone(basePrinter);
    for (const [k, v] of Object.entries(imp.printer)) {
      if (v && typeof v === 'object' && !Array.isArray(v) && p[k] && typeof p[k] === 'object' && !Array.isArray(p[k])) Object.assign(p[k], v);
      else p[k] = clone(v);
    }
    if (p.default_accel > p.max_accel) p.default_accel = p.max_accel;
    p.id = 'imported';
    p.verified = false;
    p.name = imp.printer.name || ('Imported: ' + (imp.file || 'G-code'));
    p.prefix = p.name.replace(/[^A-Za-z0-9]/g, '').slice(0, 4).toUpperCase() || 'IMP';
    p.source = 'Imported from ' + (imp.file || 'a G-code file');
    delete p.start_state;
    p.options = {};
    if (imp.start_gcode.length) p.start_gcode = imp.start_gcode.slice();
    if (imp.end_gcode.length) p.end_gcode = imp.end_gcode.slice();
    const mat = clone(baseMaterial);
    for (const [k, v] of Object.entries(imp.material)) mat[k] = v;
    mat.id = 'imported';
    mat.verified = false;
    if (has(imp.material, 'type')) mat.name = imp.material.type;
    return [p, mat];
  }

  const api = { parse, toProfiles, substitute, settings, detectSlicer };
  C3D.importer = api;
  if (isNode) module.exports = api;
})();
