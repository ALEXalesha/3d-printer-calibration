"""Import settings from a G-code the printer has already printed well (spec §4).

Reads the slicer's settings block (OrcaSlicer, ElegooSlicer, Bambu Studio, PrusaSlicer,
SuperSlicer, Cura), takes the start code (everything before the first layer) and the end
code (after the last layer), puts placeholders in place of the temperatures it found and
reports what it replaced and what it could not find. Twin: web/js/core/importer.js.
"""
import re

LAYER_MARKERS = (";LAYER_CHANGE", ";LAYER:", "; CHANGE_LAYER")
END_MARKERS = (";TYPE:Custom", ";TIME_ELAPSED:", "; filament end gcode", "; MACHINE_END_GCODE_START", ";End of Gcode",
               "; EXECUTABLE_BLOCK_END", "; CONFIG_BLOCK_START", "; prusaslicer_config = begin",
               "; SuperSlicer_config = begin")
STOP_MARKERS = ("; EXECUTABLE_BLOCK_END", ";End of Gcode", "; CONFIG_BLOCK_START", "; prusaslicer_config = begin",
                "; SuperSlicer_config = begin", ";SETTING_3 ")
DROP = re.compile(r"^(M73\b|M486\b|EXCLUDE_OBJECT_DEFINE\b|EXCLUDE_OBJECT_START\b|EXCLUDE_OBJECT_END\b|;TYPE:|;WIDTH:|;HEIGHT:|;TIME_ELAPSED:|; *thumbnail|; *[A-Za-z_][A-Za-z0-9_ ()\[\]]* = )", re.I)
_KV = re.compile(r"^; *([A-Za-z0-9_]+) *= *(.*)$")
_CURA_KV = re.compile(r"(?:^|\\n)([a-z_0-9]+) = ([^\\]*)")
FLAVORS = {"klipper": "klipper", "marlin": "marlin", "marlin2": "marlin", "marlinlegacy": "marlin",
           "reprapfirmware": "rrf", "reprap": "rrf", "rrf": "rrf", "griffin": "marlin", "ultigcode": "marlin"}
BED_TYPES = {"textured pei plate": "textured_plate_temp", "high temp plate": "hot_plate_temp",
             "smooth pei plate": "hot_plate_temp", "cool plate": "cool_plate_temp",
             "engineering plate": "eng_plate_temp", "textured cool plate": "textured_cool_plate_temp",
             "supertack plate": "supertack_plate_temp"}


def _first_num(v):
    m = re.search(r"[-+]?\d+(?:\.\d+)?", v or "")
    return float(m.group(0)) if m else None


def _shape(v):
    """printable_area / bed_shape "0x0,256x0,256x256,0x256" -> (x, y, origin, shape)."""
    pts = []
    for part in (v or "").split(","):
        m = re.match(r"^\s*([-+]?\d+(?:\.\d+)?)x([-+]?\d+(?:\.\d+)?)\s*$", part)
        if m:
            pts.append((float(m.group(1)), float(m.group(2))))
    if len(pts) < 3:
        return None
    xs, ys = [p[0] for p in pts], [p[1] for p in pts]
    x, y = max(xs) - min(xs), max(ys) - min(ys)
    origin = "center" if min(xs) < -1 and min(ys) < -1 else "corner"
    shape = "round" if len(pts) > 8 else "rect"
    if shape == "round":
        origin = "center"
    return x, y, origin, shape


def detect_slicer(head_text):
    m = re.search(r"generated by (\S+)", head_text, re.I) or re.search(r"Generated with (\S+)", head_text)
    name = (m.group(1) if m else "").lower()
    for key, sid in (("orcaslicer", "orca"), ("elegooslicer", "elegoo"), ("bambustudio", "bambu"),
                     ("prusaslicer", "prusa"), ("superslicer", "superslicer"), ("cura", "cura")):
        if key in name:
            return sid
    if ";FLAVOR:" in head_text:
        return "cura"
    return None


def settings(lines):
    """All "; key = value" pairs of the file (last value wins) plus Cura's SETTING_3."""
    out = {}
    cura = []
    for line in lines:
        if line.startswith(";SETTING_3 "):
            cura.append(line[11:])
            continue
        m = _KV.match(line)
        if m:
            out[m.group(1)] = m.group(2).strip()
    if cura:
        blob = "".join(cura)
        for k, v in _CURA_KV.findall(blob):
            out.setdefault(k, v.strip())
    return out


def detect_firmware(cfg, text_parts):
    flavor = (cfg.get("gcode_flavor") or cfg.get("FLAVOR") or "").strip().lower()
    if flavor in FLAVORS:
        return FLAVORS[flavor], "header"
    joined = "\n".join(text_parts)
    if re.search(r"^(SET_PRESSURE_ADVANCE|SET_VELOCITY_LIMIT|SET_PRINT_STATS_INFO|EXCLUDE_OBJECT_DEFINE)\b", joined, re.M):
        return "klipper", "commands"
    if re.search(r"^M572\s+D", joined, re.M) or re.search(r"^G10\s+P\d+\s+[SR]", joined, re.M):
        return "rrf", "commands"
    if re.search(r"^M572\s+S", joined, re.M):
        return "marlin", "commands"        # Prusa firmware: pressure advance as M572 S
    if re.search(r"^M900\b", joined, re.M):
        return "marlin", "commands"
    return None, None


def _region_start(lines):
    """Index of the first line of the start code and of the first layer marker."""
    begin = 0
    for i, line in enumerate(lines):
        if line.startswith("; EXECUTABLE_BLOCK_START"):
            begin = i + 1
            break
        if line.startswith(LAYER_MARKERS):
            break
    first_layer = None
    for i in range(begin, len(lines)):
        if lines[i].startswith(LAYER_MARKERS):
            first_layer = i
            break
    if begin == 0 and first_layer:
        # no block markers: skip the header comments and the thumbnail at the top
        i = 0
        while i < first_layer and (lines[i].startswith(";") or not lines[i].strip()):
            i += 1
        begin = i
    return begin, first_layer


def _region_end(lines):
    last_layer = None
    for i in range(len(lines) - 1, -1, -1):
        if lines[i].startswith(LAYER_MARKERS):
            last_layer = i
            break
    if last_layer is None:
        return None, None
    start = None
    for i in range(last_layer + 1, len(lines)):
        if lines[i].startswith(END_MARKERS):
            start = i
            break
    if start is None:
        return None, None
    stop = len(lines)
    for i in range(start, len(lines)):
        if i > start and lines[i].startswith(STOP_MARKERS):
            stop = i
            break
        if i == start and lines[i].startswith(STOP_MARKERS) and not lines[i].startswith(";TYPE:Custom"):
            return None, None
    return start, stop


def _clean(lines):
    out = []
    for line in lines:
        s = line.rstrip()
        if DROP.match(s.strip()):
            continue
        out.append(s)
    while out and not out[0].strip():
        out.pop(0)
    while out and not out[-1].strip():
        out.pop()
    return out


def _cmd(line):
    return line.split(";", 1)[0].strip().upper().split(None, 1)[0] if line.split(";", 1)[0].strip() else ""


def substitute(lines, temps, part):
    """Placeholders in place of found temperatures. -> (lines, report)."""
    t1, t, bed, ftype = temps.get("first"), temps.get("nozzle"), temps.get("bed"), temps.get("type")
    out, report = [], []

    def num_eq(s, v):
        return v is not None and abs(float(s) - v) < 1e-9

    for i, line in enumerate(lines):
        new = line
        code, sep, comment = line.partition(";")
        cmd = _cmd(line)
        if cmd in ("M104", "M109"):
            def rep(m):
                if num_eq(m.group(2), t1):
                    return m.group(1) + "{first_layer_nozzle_temp}"
                if num_eq(m.group(2), t):
                    return m.group(1) + "{nozzle_temp}"
                return m.group(0)
            code = re.sub(r"(\bS)(\d+(?:\.\d+)?)\b", rep, code)
            new = code + sep + comment
        elif cmd in ("M140", "M190"):
            code = re.sub(r"(\bS)(\d+(?:\.\d+)?)\b",
                          lambda m: m.group(1) + "{bed_temp}" if num_eq(m.group(2), bed) else m.group(0), code)
            new = code + sep + comment
        elif cmd == "M6211":
            code = re.sub(r"(\b[QRS])(\d+(?:\.\d+)?)\b",
                          lambda m: m.group(1) + "{first_layer_nozzle_temp}" if num_eq(m.group(2), t1) else m.group(0), code)
            new = code + sep + comment
        elif cmd == "SET_PRINT_STATS_INFO":
            new = re.sub(r"TOTAL_LAYER=\d+", "TOTAL_LAYER={total_layers}", line)
        elif re.search(r"\b(BED|BED_TEMP|HOTEND|EXTRUDER|EXTRUDER_TEMP|NOZZLE|NOZZLE_TEMP)=\d", code, re.I):
            def macro(mm):
                key = mm.group(1).upper()
                if key.startswith("BED"):
                    return key + "={bed_temp}" if num_eq(mm.group(2), bed) else mm.group(0)
                if num_eq(mm.group(2), t1):
                    return key + "={first_layer_nozzle_temp}"
                return mm.group(0)
            code = re.sub(r"\b(BED_TEMP|BED|HOTEND|EXTRUDER_TEMP|EXTRUDER|NOZZLE_TEMP|NOZZLE)=(\d+(?:\.\d+)?)\b", macro, code, flags=re.I)
            new = code + sep + comment
        elif line.startswith(";LAYER_COUNT:"):
            new = ";LAYER_COUNT:{total_layers}"
        elif line.startswith(";bed_level_temp:") and bed is not None and num_eq(line[16:].strip() or "nan", bed):
            new = ";bed_level_temp:{bed_temp}"
        elif line.startswith(";initial_filament:") and ftype and line[18:].strip() == ftype:
            new = ";initial_filament:{filament_type}"
        if new != line:
            report.append({"part": part, "line": i + 1, "before": line, "after": new})
        out.append(new)
    return out, report


def parse(text, file_name=""):
    """Everything found in the file. Missing fields are listed, never guessed silently."""
    lines = text.replace("\r\n", "\n").replace("\r", "\n").split("\n")
    begin, first_layer = _region_start(lines)
    e0, e1 = _region_end(lines)
    head_text = "\n".join(lines[:min(len(lines), 400)])
    tail = lines[max(0, len(lines) - 4000):]
    cfg = settings(lines[:min(len(lines), first_layer or 0)] + tail)
    slicer = detect_slicer(head_text)
    start_raw = lines[begin:first_layer] if first_layer is not None else []
    end_raw = lines[e0:e1] if e0 is not None else []
    for line in lines[:min(len(lines), 400)]:
        if line.startswith(";FLAVOR:"):
            cfg.setdefault("FLAVOR", line[8:].strip())
    fw, fw_from = detect_firmware(cfg, start_raw + end_raw + lines[first_layer or 0:(first_layer or 0) + 3000])

    found, missing = {}, []
    p, m = {}, {}

    def num(*keys):
        for k in keys:
            if k in cfg:
                v = _first_num(cfg[k])
                if v is not None:
                    return v
        return None

    sh = _shape(cfg.get("printable_area") or cfg.get("bed_shape"))
    if sh:
        p["bed"] = {"x": sh[0], "y": sh[1], "origin": sh[2], "shape": sh[3]}
    elif num("machine_width") and num("machine_depth"):
        p["bed"] = {"x": num("machine_width"), "y": num("machine_depth"), "origin": "corner", "shape": "rect"}
    z = num("printable_height", "max_print_height", "machine_height")
    if z is not None:
        p.setdefault("bed", {})["z"] = z
    for key, keys in (("nozzle", ("nozzle_diameter", "machine_nozzle_size")),
                      ("filament_diameter", ("filament_diameter", "material_diameter")),
                      ("travel_speed", ("travel_speed", "speed_travel"))):
        v = num(*keys)
        if v is not None:
            p[key] = v
    acc = num("machine_max_acceleration_x", "machine_max_acceleration_extruding")
    if acc:
        p["max_accel"] = int(acc)
    spd = num("machine_max_speed_x", "machine_max_feedrate_x")
    if spd:
        p["max_speed"] = spd
    dacc = num("default_acceleration", "outer_wall_acceleration")
    if dacc:
        p["default_accel"] = int(dacc)
    r = {}
    for key, keys in (("length", ("retraction_length", "retract_length", "retraction_amount")),
                      ("speed", ("retraction_speed", "retract_speed")),
                      ("z_hop", ("z_hop", "retract_lift", "retraction_hop"))):
        v = num(*keys)
        if v is not None:
            r[key] = v
    if r:
        p["retract"] = r
    if fw:
        p["firmware"] = fw
        if fw == "marlin" and re.search(r"^M572\s+S", "\n".join(start_raw + lines[first_layer or 0:(first_layer or 0) + 3000]), re.M):
            p["fw_overrides"] = {"pressure_advance": "M572 S{v}"}
    name = cfg.get("printer_model") or cfg.get("printer_settings_id") or ""
    if not name:
        for line in start_raw:
            if line.startswith(";printer_model:"):
                name = line[15:].strip()
                break
    if name:
        p["name"] = name.strip().strip('"')

    ftype = (cfg.get("filament_type") or cfg.get("material_type") or "").split(";")[0].strip().strip('"') or None
    if ftype:
        m["type"] = ftype.upper()
    t_print = num("nozzle_temperature", "temperature", "material_print_temperature")
    t_first = num("nozzle_temperature_initial_layer", "first_layer_temperature", "material_print_temperature_layer_0")
    bed = None
    btype = (cfg.get("curr_bed_type") or "").strip().lower()
    if btype in BED_TYPES:
        bed = num(BED_TYPES[btype] + "_initial_layer", BED_TYPES[btype])
    if bed is None:
        bed = num("first_layer_bed_temperature", "bed_temperature", "material_bed_temperature_layer_0", "material_bed_temperature")
    # fall back to the start code itself
    def from_code(cmds):
        for line in start_raw:
            if _cmd(line) in cmds:
                mm = re.search(r"\bS(\d+(?:\.\d+)?)", line.split(";", 1)[0])
                if mm and float(mm.group(1)) > 0:
                    return float(mm.group(1))
        return None
    if t_first is None:
        t_first = from_code(("M109",)) or from_code(("M104",))
    if t_print is None:
        t_print = t_first
    if bed is None:
        bed = from_code(("M190",)) or from_code(("M140",))
    if t_print is not None:
        m["nozzle_temp"] = int(round(t_print))
    if t_first is not None:
        m["first_layer_temp"] = int(round(t_first))
    if bed is not None:
        m["bed"] = int(round(bed))
    pa = num("pressure_advance")
    if pa is not None:
        m["pa_default"] = pa
    mvs = num("filament_max_volumetric_speed")
    if mvs:
        m["mvs"] = mvs

    temps = {"first": t_first, "nozzle": t_print, "bed": bed, "type": m.get("type")}
    start, rep1 = substitute(_clean(start_raw), temps, "start")
    end, rep2 = substitute(_clean(end_raw), temps, "end")

    wanted = ["bed.x", "bed.y", "bed.z", "nozzle", "filament_diameter", "firmware", "retract.length",
              "retract.speed", "retract.z_hop", "material.nozzle_temp", "material.first_layer_temp", "material.bed",
              "material.type", "start_gcode", "end_gcode"]
    have = {"bed.x": "x" in p.get("bed", {}), "bed.y": "y" in p.get("bed", {}), "bed.z": "z" in p.get("bed", {}),
            "nozzle": "nozzle" in p, "filament_diameter": "filament_diameter" in p, "firmware": "firmware" in p,
            "retract.length": "length" in r, "retract.speed": "speed" in r, "retract.z_hop": "z_hop" in r,
            "material.nozzle_temp": "nozzle_temp" in m, "material.first_layer_temp": "first_layer_temp" in m,
            "material.bed": "bed" in m, "material.type": "type" in m,
            "start_gcode": bool(start), "end_gcode": bool(end)}
    found = [k for k in wanted if have[k]]
    missing = [k for k in wanted if not have[k]]
    warnings = []
    if slicer == "bambu":
        warnings.append("bambu")
    if not fw:
        warnings.append("firmware_unknown")
    return {"slicer": slicer, "file": file_name, "printer": p, "material": m, "start_gcode": start,
            "end_gcode": end, "replaced": rep1 + rep2, "found": found, "missing": missing,
            "firmware_from": fw_from, "warnings": warnings}


def to_profiles(imp, base_printer, base_material):
    """Full printer and material profiles: what the file gave, the rest from the bases."""
    import copy
    p = copy.deepcopy(base_printer)
    for k, v in imp["printer"].items():
        if isinstance(v, dict) and isinstance(p.get(k), dict):
            p[k].update(v)
        else:
            p[k] = v
    if p["default_accel"] > p["max_accel"]:
        p["default_accel"] = p["max_accel"]
    p["id"] = "imported"
    p["verified"] = False
    p["name"] = imp["printer"].get("name") or ("Imported: " + (imp.get("file") or "G-code"))
    p["prefix"] = re.sub(r"[^A-Za-z0-9]", "", p["name"])[:4].upper() or "IMP"
    p["source"] = "Imported from " + (imp.get("file") or "a G-code file")
    p.pop("start_state", None)
    p["options"] = {}
    if imp["start_gcode"]:
        p["start_gcode"] = imp["start_gcode"]
    if imp["end_gcode"]:
        p["end_gcode"] = imp["end_gcode"]
    mat = copy.deepcopy(base_material)
    for k, v in imp["material"].items():
        mat[k] = v
    mat["id"] = "imported"
    mat["verified"] = False
    if "type" in imp["material"]:
        mat["name"] = imp["material"]["type"]
    return p, mat
