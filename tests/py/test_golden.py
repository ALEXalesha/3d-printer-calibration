"""The main law: Elegoo Centauri Carbon + PETG/PLA with default settings give the same
bytes as reference/calibration.py (tests/golden), except for one listed line."""
import hashlib
import re
from pathlib import Path

import pytest

from calib3d.core import generator as G
from calib3d.core import profiles as P

GOLDEN = Path(__file__).resolve().parents[1] / "golden"

# The only allowed difference: line 2, the name and version of the program.
ALLOWED = {1: (re.compile(r"^; generated by calibration\.py \((.+)\)$"),
               re.compile(r"^; generated by Calibrate 3D Printer \d+\.\d+\.\d+ \((.+)\)$"))}

CASES = [(t, m) for t in G.TEST_IDS for m in ("petg", "pla")]


def test_golden_files_are_intact():
    sums = {}
    for line in (GOLDEN / "SHA256SUMS").read_text(encoding="ascii").splitlines():
        h, name = line.split(" *")
        sums[name] = h
    assert len(sums) == 20
    for name, h in sums.items():
        assert hashlib.sha256((GOLDEN / name).read_bytes()).hexdigest() == h, name


@pytest.mark.parametrize("test_id,mat", CASES)
def test_reference_profile_matches_golden(test_id, mat):
    r = G.generate(P.printer("elegoo-centauri-carbon"), P.material(mat), test_id)
    gold_path = GOLDEN / r.name
    assert gold_path.exists(), f"file name changed: {r.name}"
    gold = gold_path.read_bytes().decode("utf-8").split("\n")
    ours = r.text.split("\n")
    assert len(ours) == len(gold)
    for i, (a, b) in enumerate(zip(gold, ours)):
        if a == b:
            continue
        assert i in ALLOWED, f"line {i + 1} differs:\n  golden: {a}\n  ours:   {b}"
        old, new = ALLOWED[i]
        ma, mb = old.match(a), new.match(b)
        assert ma and mb and ma.group(1) == mb.group(1), f"line {i + 1}: {a!r} vs {b!r}"
    assert r.text.endswith("\n") and not r.text.endswith("\n\n")
