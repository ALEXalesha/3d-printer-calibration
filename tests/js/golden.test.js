// The main law for the JavaScript core: Centauri Carbon + PETG/PLA = tests/golden, byte for
// byte, except line 2 (name and version of the program).
'use strict';
const test = require('node:test');
const assert = require('node:assert');
const fs = require('fs');
const path = require('path');
const C3D = require('./helpers');

const GOLDEN = path.join(__dirname, '..', 'golden');
const OLD = /^; generated by calibration\.py \((.+)\)$/;
const NEW = /^; generated by Calibrate 3D Printer \d+\.\d+\.\d+ \((.+)\)$/;

for (const tid of C3D.generator.TEST_IDS) {
  for (const mat of ['petg', 'pla']) {
    test(`golden ${tid} ${mat}`, () => {
      const r = C3D.generator.generate(C3D.profiles.printer('elegoo-centauri-carbon'), C3D.profiles.material(mat), tid);
      const file = path.join(GOLDEN, r.name);
      assert.ok(fs.existsSync(file), 'file name changed: ' + r.name);
      const gold = fs.readFileSync(file, 'utf8').split('\n');
      const ours = r.text.split('\n');
      assert.strictEqual(ours.length, gold.length);
      for (let i = 0; i < gold.length; i++) {
        if (gold[i] === ours[i]) continue;
        assert.strictEqual(i, 1, `line ${i + 1} differs:\n  golden: ${gold[i]}\n  ours:   ${ours[i]}`);
        const a = OLD.exec(gold[i]), b = NEW.exec(ours[i]);
        assert.ok(a && b && a[1] === b[1], `line 2: ${gold[i]} vs ${ours[i]}`);
      }
    });
  }
}
